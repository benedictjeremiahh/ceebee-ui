/**
 * The changelog has one source: the package's own CHANGELOG.md, written by the release.
 * This turns it into a docs page so nobody maintains a second copy that can drift.
 *
 * MDX reads `{` and `<` as expression and element syntax, so everything outside a fenced
 * code block is escaped before it becomes a page.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const here = dirname(new URL(import.meta.url).pathname);
const source = resolve(here, '../packages/ui/CHANGELOG.md');
const target = resolve(here, 'app/changelog/page.mdx');

const escape = (text) => text.replaceAll('{', '&#123;').replaceAll('}', '&#125;').replaceAll('<', '&lt;');

const body = readFileSync(source, 'utf8')
  .split(/(```[\s\S]*?```)/g)
  .map((segment) => (segment.startsWith('```') ? segment : escape(segment)))
  .join('')
  /* The file's own H1 is the package name; the page supplies its own title. */
  .replace(/^# @ceebee\/ui\n+/, '');

writeFileSync(
  target,
  `{/* Generated by docs/changelog.mjs from packages/ui/CHANGELOG.md — edit the changeset, not this file. */}

# Changelog

Every released version, and what breaks when you move between them. Written from the changesets that
shipped with each change.

${body.trim()}
`,
);

console.log(`Changelog page written from ${source.split('/').slice(-2).join('/')}`);
