// What the docs can prove about the library it documents, decided at build time.
//
// The version, the exported surface, and the Skins are facts about the package this deployment was
// built against. Reading them at build time rather than at request time keeps the health endpoint
// from importing the whole library on every call, and keeps it honest: it reports the build that is
// actually serving, not whatever happens to be on disk.
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';

const packageDir = new URL('../packages/ui/', import.meta.url);
const outFile = new URL('./lib/ui-manifest.generated.ts', import.meta.url);

const manifest = JSON.parse(await readFile(new URL('package.json', packageDir), 'utf8'));
const skins = (await readdir(new URL('src/skins/', packageDir)))
  .filter((file) => file.endsWith('.css'))
  .map((file) => file.replace(/\.css$/, ''))
  .sort();

const exports = {
  server: await countValueExports(new URL('src/index.ts', packageDir)),
  client: await countValueExports(new URL('src/client.ts', packageDir)),
};

// `export type` lines describe the API without adding anything a consumer can render, so they are
// not counted as exported surface.
async function countValueExports(file) {
  const source = await readFile(file, 'utf8');
  const names = new Set();
  for (const match of source.matchAll(/^export\s+(?!type\b)\{([^}]*)\}/gm)) {
    for (const name of match[1].split(',')) {
      const local = name.trim().split(/\s+as\s+/).pop();
      if (local) names.add(local);
    }
  }
  return names.size;
}

await mkdir(new URL('./lib/', import.meta.url), { recursive: true });
await writeFile(
  outFile,
  `// Generated by ui-manifest.mjs during predev/prebuild. Do not edit.\n` +
    `import type { UiManifest } from './ui-manifest';\n\n` +
    `export const UI_MANIFEST: UiManifest = ${JSON.stringify(
      { name: manifest.name, version: manifest.version, skins, exports },
      null,
      2,
    )};\n`,
);
console.log(`ui manifest written for ${manifest.name}@${manifest.version}`);
