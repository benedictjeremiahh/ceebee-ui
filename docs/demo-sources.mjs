// The real source of every demo on the docs site, captured at build time.
//
// A demo card's source pane has to show the code that is actually running, so the listing is the
// file itself — `'use client'` directive, imports, strict-mode guards and all — not a summary of it.
//
// One module is written per component directory so a page carries its own component's sources and
// nothing else.
import { readFile, readdir, writeFile } from 'node:fs/promises';

const componentsDir = new URL('./components/', import.meta.url);
const sections = ['general', 'layout', 'navigation', 'data-entry', 'data-display', 'feedback', 'other'];

/** Files that live beside the demos without being demos themselves. */
const notADemo = (file) =>
  !file.endsWith('.tsx') || file === 'showcase.tsx' || file === 'iframe-demo.tsx';

let components = 0;
let demos = 0;

for (const section of sections) {
  const sectionDir = new URL(`${section}/`, componentsDir);
  const entries = await readdir(sectionDir, { withFileTypes: true });

  for (const entry of entries.filter((candidate) => candidate.isDirectory())) {
    const componentDir = new URL(`${entry.name}/`, sectionDir);
    const files = (await readdir(componentDir)).filter((file) => !notADemo(file)).sort();
    if (files.length === 0) continue;

    const sources = {};
    for (const file of files) {
      sources[file.replace(/\.tsx$/, '')] = await readFile(new URL(file, componentDir), 'utf8');
    }

    await writeFile(
      new URL('sources.generated.ts', componentDir),
      `// Generated by demo-sources.mjs during predev/prebuild. Do not edit.\n` +
        `export const sources: Record<string, string> = ${JSON.stringify(sources, null, 2)};\n`,
      'utf8',
    );
    components += 1;
    demos += files.length;
  }
}

console.log(`Captured ${demos} demo sources across ${components} components.`);
